import streamlit as st
import pandas as pd
import yfinance as yf

from live_pipeline import analyze_stock


# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="AutoML Market Intelligence",
    page_icon="📈",
    layout="wide"
)


# --------------------------------------------------
# DASHBOARD HEADER
# --------------------------------------------------

st.title("📈 AutoML Market Intelligence")
st.subheader(
    "Market Regime Detection & Risk-Adjusted "
    "Stock Movement Prediction"
)

st.caption(
    "Design Auto ML for Market Regime Detection "
    "and Risk Adjusted Stock Movement Prediction"
)

st.markdown(
    """
    This dashboard uses a trained AutoML model and a
    saved market-regime detector to analyze stock data.
    """
)

st.divider()


# --------------------------------------------------
# STOCK SELECTION
# --------------------------------------------------

st.sidebar.header("Analysis Settings")

ticker = st.sidebar.selectbox(
    "Select stock",
    ["AAPL"],
    index=0
)

st.sidebar.info(
    "This prototype currently supports Apple (AAPL) only."
)

analyze_button = st.sidebar.button(
    "Analyze Stock",
    type="primary",
    width="stretch"
)


# --------------------------------------------------
# ANALYSIS
# --------------------------------------------------

if analyze_button:

    with st.spinner(
        "Fetching market data and running AutoML analysis..."
    ):

        try:
            result = analyze_stock(ticker)

            st.session_state["analysis_result"] = result

        except Exception as error:
            st.error(f"Analysis failed: {error}")


# --------------------------------------------------
# DISPLAY RESULTS
# --------------------------------------------------

if "analysis_result" not in st.session_state:

    st.info(
        "Select a stock from the sidebar and click "
        "'Analyze Stock' to begin."
    )

else:

    result = st.session_state["analysis_result"]

    st.markdown(f"## Analysis: {result['ticker']}")

    st.caption(
        f"Latest available data date: {result['data_date']}"
    )

    # Main metrics
    col1, col2, col3, col4 = st.columns(4)

    col1.metric(
        "Latest Closing Price",
        f"${result['latest_close']:.2f}"
    )

    col2.metric(
        "Predicted Direction",
        result["predicted_direction"]
    )

    col3.metric(
        "Probability of Upward Movement",
        f"{result['probability_up']:.1%}"
    )

    col4.metric(
        "Market Regime",
        result["market_regime"]
    )

    st.divider()

    # Signal and risk
    left, right = st.columns(2)

    with left:

        st.subheader("Model Decision Signal")

        signal = result["signal"]

        if signal == "BUY":
            st.success(f"Signal: {signal}")

        elif signal == "AVOID":
            st.error(f"Signal: {signal}")

        else:
            st.warning(f"Signal: {signal}")

        st.caption(
            "This signal is generated by predefined "
            "rules applied to the model prediction."
        )

    with right:

        st.subheader("Risk Assessment")

        st.metric(
            "Volatility",
            f"{result['volatility']:.2%}"
        )

        st.metric(
            "Risk Classification",
            result["risk_level"]
        )

        st.caption(
            "Risk classification compares current volatility "
            "with the threshold saved in your project."
        )

    st.divider()

    # Feature table
    st.subheader("Financial Feature Analysis")

    features = pd.DataFrame(
        result["features"].items(),
        columns=["Feature", "Value"]
    )

    features["Value"] = features["Value"].apply(
        lambda value: f"{value:.5f}"
    )

    st.dataframe(
        features,
        width="stretch",
        hide_index=True
    )

    st.divider()

    # Historical chart
    st.subheader("Apple Historical Closing Prices")

    try:

        history = yf.Ticker(
            result["ticker"]
        ).history(
            period="6mo",
            interval="1d",
            auto_adjust=True
        )

        if not history.empty:

            st.line_chart(
                history["Close"],
                width="stretch"
            )

        else:

            st.warning(
                "Historical chart data is unavailable."
            )

    except Exception as error:

        st.warning(
            f"Could not load the historical chart: {error}"
        )

    st.divider()

    # Export results
    st.subheader("Export Analysis")

    export_data = {
        "Ticker": result["ticker"],
        "Data Date": result["data_date"],
        "Latest Close": result["latest_close"],
        "Predicted Direction": result["predicted_direction"],
        "Probability Up": result["probability_up"],
        "Market Regime": result["market_regime"],
        "Daily Return": result["daily_return"],
        "Volatility": result["volatility"],
        "Risk Level": result["risk_level"],
        "Signal": result["signal"]
    }

    export_df = pd.DataFrame([export_data])

    st.download_button(
        label="Download Analysis as CSV",
        data=export_df.to_csv(index=False),
        file_name="automl_stock_analysis.csv",
        mime="text/csv"
    )


# --------------------------------------------------
# FOOTER
# --------------------------------------------------

st.divider()

st.caption(
    "Academic project prototype. Predictions are estimates, "
    "not guarantees of future performance or financial advice. "
    "Market data availability and freshness depend on the provider."
)